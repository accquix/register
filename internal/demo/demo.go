// Package demo loads a database with fictional subjects so that the API can be tried in seconds,
// without downloading the registers (D41). The data go through the normal sync code: an
// in-process server imitates the RPO bucket and the Financial Administration list exports, in
// their real layouts. A loaded database is marked as a demo for good: the API labels every answer,
// and the sync refuses to write real data into it.
package demo

import (
	"context"
	"errors"
	"fmt"
	"log/slog"
	"net"
	"net/http"
	"time"

	"github.com/jackc/pgx/v5"

	"github.com/accquix/register/internal/ingest"
	"github.com/accquix/register/internal/lookup"
	"github.com/accquix/register/internal/sources/fs"
	"github.com/accquix/register/internal/sources/rpo"
	"github.com/accquix/register/internal/syncer"
	"github.com/accquix/register/internal/synthetic"
)

// Attribution replaces the sources' attribution on every answer of a demo database.
var Attribution = []string{
	"DEMO DATA: fictional subjects generated by Accquix Register (demo mode). Not taken from any register; do not rely on them.",
}

// ErrRealData: demo refuses a database that already holds register data.
var ErrRealData = errors.New("this database already holds register data: load the demo into a new, empty database")

// ErrDemoDatabase: the sync refuses a demo database, so that real and fictional data never mix.
var ErrDemoDatabase = errors.New("this database holds demo data (accquix-register demo): point the sync at a new, empty database for real data")

// Querier is what IsDemo needs: a connection or a pool.
type Querier interface {
	QueryRow(ctx context.Context, sql string, args ...any) pgx.Row
}

// IsDemo reports whether the database was loaded by demo.
func IsDemo(ctx context.Context, q Querier) (bool, error) {
	var demo bool
	err := q.QueryRow(ctx, `SELECT coalesce((SELECT demo_since IS NOT NULL FROM register_setup WHERE only_row), false)`).Scan(&demo)
	return demo, err
}

// Summary is what Load reports.
type Summary struct {
	Subjects      int
	AlreadyLoaded bool
}

// Load marks an empty database as a demo and fills it with the fictional data set. It is safe to
// run again: a demo database that is already complete is left as it is.
func Load(ctx context.Context, conn *pgx.Conn, workDir string, log *slog.Logger) (Summary, error) {
	if log == nil {
		log = slog.New(slog.DiscardHandler)
	}
	var demo, published, complete bool
	err := conn.QueryRow(ctx, `SELECT
  coalesce((SELECT demo_since IS NOT NULL FROM register_setup WHERE only_row), false),
  EXISTS (SELECT 1 FROM sync_source WHERE published_as_of IS NOT NULL),
  (SELECT count(*) FROM sync_source WHERE published_as_of IS NOT NULL) = $1`, len(lookup.AllSources)).Scan(&demo, &published, &complete)
	if err != nil {
		return Summary{}, fmt.Errorf("demo: %w", err)
	}
	if published && !demo {
		return Summary{}, ErrRealData
	}
	set := Dataset(time.Now().UTC())
	if demo && complete {
		// A demo database that outlived an upgrade may owe a search rebuild (migration 00006). The
		// sync refuses a demo database, so nothing else would do it and the API would stay at 503.
		if err := syncer.RebuildIfOwed(ctx, conn, log); err != nil {
			return Summary{}, fmt.Errorf("demo: rebuild the search layer: %w", err)
		}
		return Summary{Subjects: len(set.Records), AlreadyLoaded: true}, nil
	}
	// Mark first: a load that dies half-way still leaves a database that says it is a demo.
	if _, err := conn.Exec(ctx, `UPDATE register_setup SET demo_since = coalesce(demo_since, now()) WHERE only_row`); err != nil {
		return Summary{}, fmt.Errorf("demo: mark the database: %w", err)
	}

	bucket, lists := synthetic.NewBucket(), synthetic.NewFSServer()
	bucket.PutSnapshot(set.SnapshotDate, set.Records, len(set.Records)+1)
	for slug, items := range set.Lists {
		lists.Put(slug, synthetic.FSZip(slug, set.ListDate, items))
	}
	mux := http.NewServeMux()
	mux.Handle("/rpo/", http.StripPrefix("/rpo", bucket))
	mux.Handle("/fs/", http.StripPrefix("/fs", lists))
	ln, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		return Summary{}, fmt.Errorf("demo: %w", err)
	}
	srv := &http.Server{Handler: mux, ReadHeaderTimeout: 5 * time.Second}
	go func() { _ = srv.Serve(ln) }()
	defer func() { _ = srv.Close() }()
	base := "http://" + ln.Addr().String()

	if err := syncer.NewRPO(conn, syncer.RPOConfig{Bucket: rpo.NewBucket(base + "/rpo"), WorkDir: workDir, Log: log}).Run(ctx); err != nil {
		return Summary{}, fmt.Errorf("demo: %w", err)
	}
	if err := syncer.NewFS(conn, syncer.FSConfig{Client: fs.NewClient(base + "/fs"), WorkDir: workDir, SkipMinRows: true, Log: log}).Run(ctx); err != nil {
		return Summary{}, fmt.Errorf("demo: %w", err)
	}
	if ok, err := ingest.SetupConfirmed(ctx, conn); err != nil {
		return Summary{}, fmt.Errorf("demo: %w", err)
	} else if !ok {
		if err := ingest.ConfirmNoObjections(ctx, conn); err != nil {
			return Summary{}, fmt.Errorf("demo: confirm the installation: %w", err)
		}
	}
	return Summary{Subjects: len(set.Records)}, nil
}
